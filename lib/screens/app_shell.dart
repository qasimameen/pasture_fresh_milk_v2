/// Main application shell housing the 5-tab navigation bar and preserving
/// tab state via [IndexedStack] (plan.md C-M1; Section 1.7 nav bar).
class AppShell extends ConsumerStatefulWidget {
  /// Creates the app navigation shell.
  const AppShell({
    super.key,
    this.initialIndex = 0,
  });

  /// The tab index to display initially (0 = Home, 1 = Customers, etc.).
  final int initialIndex;

  @override
  ConsumerState<AppShell> createState() => _AppShellState();
}

class _AppShellState extends ConsumerState<AppShell> {
  late int _currentIndex;
  bool _hasAttemptedAutoGenerate = false;
  final GlobalKey<CustomersScreenState> _customersKey = GlobalKey<CustomersScreenState>();
  final GlobalKey<DeliveriesScreenState> _deliveriesKey = GlobalKey<DeliveriesScreenState>();

  @override
  void initState() {
    super.initState();
    _currentIndex = widget.initialIndex.clamp(0, 4);
    
    WidgetsBinding.instance.addPostFrameCallback((_) {
      _autoGenerateDeliveries();
    });
  }

  Future<void> _autoGenerateDeliveries() async {
    if (_hasAttemptedAutoGenerate) return;
    _hasAttemptedAutoGenerate = true;
    
    if (Platform.environment.containsKey('FLUTTER_TEST')) return;
    
    try {
      final customers = await ref.read(customerListProvider.future);
      if (customers.isEmpty) return;
      
      final repo = ref.read(deliveryRepositoryProvider);
      final now = DateTime.now();
      
      int totalGenerated = 0;
      totalGenerated += await repo.generateDailyDeliveries(now, 'morning', customers);
      totalGenerated += await repo.generateDailyDeliveries(now, 'evening', customers);
      
      if (totalGenerated > 0) {
        ref.invalidate(deliveryListProvider);
        ref.invalidate(deliveryStatsProvider);
        ref.invalidate(dashboardProvider);
      }
    } catch (_) {
      // Silently ignore auto-generation errors on startup
    }
  }

  void _onTabSelected(int index) {
    if (_currentIndex != index) {
      if (index == 0) {
        ref.invalidate(dashboardProvider);
      } else if (index == 1) {
        ref.invalidate(allCustomersProvider);
        ref.invalidate(customerStatsProvider);
        _customersKey.currentState?.resetFilters();
      } else if (index == 2) {
        ref.invalidate(deliveryListProvider);
        ref.invalidate(deliveryStatsProvider);
        _deliveriesKey.currentState?.resetFilters();
      } else if (index == 3) {
        ref.invalidate(todayPaymentsProvider);
        ref.invalidate(todayCashTotalProvider);
        ref.invalidate(monthlyCollectionProvider);
      }
      setState(() {
        _currentIndex = index;
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    return AnnotatedRegion<SystemUiOverlayStyle>(
      value: SystemUiOverlayStyle.dark.copyWith(
        statusBarColor: Colors.transparent,
      ),
      child: Scaffold(
        backgroundColor: AppColors.scaffold,
        body: IndexedStack(
          index: _currentIndex,
          children: <Widget>[
            HomeScreen(
              key: const Key('tab_view_home'),
              onNavigateToTab: _onTabSelected,
            ),
            CustomersScreen(
              key: _customersKey,
            ),
            DeliveriesScreen(
              key: _deliveriesKey,
            ),
            const PaymentsScreen(
              key: Key('tab_view_payments'),
            ),

            const SuppliersScreen(
              key: Key('tab_view_suppliers'),
            ),
          ],
        ),
        bottomNavigationBar: BottomNavBar(
          currentIndex: _currentIndex,
          onTap: _onTabSelected,
        ),
      ),
    );
  }
}
